PHOTO_URL_RE = re.compile(r"background-image:\s*url\((['\"]?)(.*?)\1\)")
# извлечённый URL мы сами скачиваем (см. send_telegram_photo) — ограничиваем
# его хостом CDN самого Telegram, чтобы HTML стороннего канала не мог
# подсунуть произвольный адрес для скачивания
ALLOWED_PHOTO_HOST_RE = re.compile(r"^https://[a-z0-9-]+\.telesco\.pe/", re.IGNORECASE)


def extract_photo_urls(msg_div):
    # альбом (несколько фото у одного поста) — все они лежат внутри того же
    # блока сообщения, каждое своим .tgme_widget_message_photo_wrap
    urls = []
    for wrap in msg_div.select(".tgme_widget_message_photo_wrap"):
        m = PHOTO_URL_RE.search(wrap.get("style", ""))
        if m and ALLOWED_PHOTO_HOST_RE.match(m.group(2)) and m.group(2) not in urls:
            urls.append(m.group(2))
    return urls


def fetch_channel_posts(channel, before=None):
    """Читает посты публичного канала через t.me/s/<channel> — открытую
    веб-версию, не требующую авторизации. before — id сообщения, "старше
    которого" запросить следующую страницу (для постраничной подгрузки)."""
    url = f"https://t.me/s/{channel}"
    if before:
        url += f"?before={before}"
    resp = requests.get(url, headers=HEADERS, timeout=15)
    resp.raise_for_status()

    soup = BeautifulSoup(resp.text, "html.parser")
    posts = []

    for msg_div in soup.select("div.tgme_widget_message"):
        data_post = msg_div.get("data-post")
        if not data_post or "/" not in data_post:
            continue

        try:
            msg_id = int(data_post.split("/")[-1])
        except ValueError:
            continue

        text_div = msg_div.select_one(".tgme_widget_message_text")
        text = text_div.get_text("\n").strip() if text_div else ""
        if not text:
            continue

        # ссылки на соцсети (VK, WhatsApp, Instagram) часто оформляют как
        # текст вида "Ссылка на автора поста в VK" — сам URL виден только в
        # href, get_text() его не отдаёт. Дописываем такие href в конец
        # текста, чтобы их подхватил обычный поиск контактов по CONTACT_RE
        if text_div:
            social_links = [
                a["href"] for a in text_div.select("a[href]")
                if any(d in a["href"] for d in SOCIAL_LINK_DOMAINS)
            ]
            if social_links:
                text += "\n" + "\n".join(social_links)

        time_tag = msg_div.select_one("time")
        date_label = ""
        post_dt = None
        if time_tag and time_tag.get("datetime"):
            try:
                post_dt = datetime.fromisoformat(time_tag["datetime"])
                date_label = post_dt.strftime("%d.%m %H:%M")
            except ValueError:
                date_label = ""

        posts.append({
            "id": msg_id,
            "channel": channel,
            "date": date_label,
            "datetime": post_dt,
            # раньше обрезали до 500 символов — контакты и залог часто
            # пишут в конце поста и они терялись ещё до попытки их найти
            "text": text[:3000],
            "link": f"https://t.me/{channel}/{msg_id}",
            "photos": extract_photo_urls(msg_div),
        })

    return posts


def fetch_channel_posts_since(channel, cutoff_dt, max_pages=15):
    """Собирает посты канала не старше cutoff_dt, подгружая более старые
    страницы (before=), пока не упрёмся в границу по времени или в лимит
    страниц (защита от каналов с огромной историей за 15 минут)."""
    all_posts = []
    before = None
    for _ in range(max_pages):
        page = fetch_channel_posts(channel, before=before)
        if not page:
            break

        stop = False
        for post in page:
            dt = post.get("datetime")
            if dt is not None and dt < cutoff_dt:
                stop = True
                continue
            all_posts.append(post)

        if stop:
            break

        before = min(p["id"] for p in page)

    return all_posts


_pending_scan_timer = None
_scan_lock = threading.Lock()


def _schedule_recent_scan(delay=3.0):
    # сканирование каналов может занять много времени (постраничная
    # подгрузка истории), поэтому запускаем в фоновом потоке — иначе
    # слушатель не сможет обработать следующие нажатия/команды, пока
    # скан не закончится. Debounce: несколько нажатий подряд (например,
    # отметили сразу 3 галочки) откладывают запуск, а не плодят по скану
    # на каждое нажатие — сработает только последний, спустя `delay` сек
    # тишины
    global _pending_scan_timer
    # снимок фильтров/каналов делаем СЕЙЧАС, в вызывающем потоке — иначе
    # фоновый таймер читал бы общий config уже во время скана, пока
    # основной поток мог успеть изменить его новым нажатием кнопки
    channels_snapshot = list(config["channels"])
    filters_snapshot = copy.deepcopy(config["filters"])
    with _scan_lock:
        if _pending_scan_timer is not None:
            _pending_scan_timer.cancel()
        _pending_scan_timer = threading.Timer(
            delay,
            send_recent_matching_ads,
            kwargs={"channels": channels_snapshot, "filters": filters_snapshot},
        )
        _pending_scan_timer.daemon = True
        _pending_scan_timer.start()


def _post_key(post):
    # уникальный идентификатор поста независимо от того, каким фильтром он
    # был найден — используется, чтобы не присылать один и тот же пост
    # повторно ни при плановом скане, ни при ручном "Применить" после смены
    # фильтра (см. state["sent_post_ids"])
    return f"{post['channel']}/{post['id']}"


# сколько последних отправленных постов помним — плановый скан и так не
# перечитывает старое благодаря state["last_ids"], а вот ручной "Применить"
# смотрит на последние 48 часов заново при каждом нажатии, поэтому именно
# ему нужен персистентный список уже отправленного, а не только курсор по id
SENT_POST_IDS_LIMIT = 1000


def send_recent_matching_ads(hours=48, channels=None, filters=None):
    # после смены фильтра пользователем — сразу показываем всё подходящее
    # за последние `hours`, а не ждать следующего планового скана каналов
    cutoff = datetime.now(timezone.utc) - timedelta(hours=hours)
    if channels is None:
        channels = config["channels"]
    if filters is None:
        filters = config["filters"]

    # читаем свежим с диска, а не из общего state в памяти — этот вызов
    # часто идёт из непрерывного слушателя, чей state в памяти мог устареть
    # за время его работы (плановый скан обновляет sent_post_ids отдельным
    # процессом). Саму пометку "отправлено" ставит send_digest — здесь
    # только фильтруем то, что уже отправлялось раньше
    sent_ids_set = set(load_json(STATE_PATH, {}).get("sent_post_ids", []))

    matches = []
    seen_word_lists = []
    for channel in channels:
        try:
            posts = fetch_channel_posts_since(channel, cutoff)
        except Exception as e:
            log(f"Не удалось прочитать канал {channel} (проверка по новому фильтру): {e}")
            continue

        for post in posts:
            if not matches_filters(post["text"], filters):
                continue
            if _post_key(post) in sent_ids_set:
                # уже отправляли этот пост раньше (при любом фильтре) —
                # не дублируем его только из-за того, что он снова подошёл
                continue
            words = extract_signature_words(post["text"])
            if is_duplicate(words, seen_word_lists):
                continue
            seen_word_lists.append(list(words))
            matches.append(post)

    if not matches:
        send_telegram_message(f"По новому фильтру за последние {hours} ч. подходящих объявлений не нашлось.")
        return

    send_telegram_message(f"По новому фильтру за последние {hours} ч. нашлось: {len(matches)}")
    send_digest(matches)


