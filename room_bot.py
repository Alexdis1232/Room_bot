def get_telegram_updates(poll_timeout=0):
    offset = state.get("last_update_id", 0) + 1
    url = f"https://api.telegram.org/bot{BOT_TOKEN}/getUpdates"
    try:
        resp = requests.get(
            url,
            params={"offset": offset, "timeout": poll_timeout},
            timeout=poll_timeout + 15,
        )
        resp.raise_for_status()
        return resp.json().get("result", [])
    except Exception as e:
        log(f"Не удалось получить обновления от Telegram: {e}")
        return []


def handle_command(text):
    if text.strip() == FILTERS_MENU_BUTTON:
        show_filters_menu()
        return

    if text.strip() == FILTERS_RESET_BUTTON:
        config["filters"]["price_ranges"] = []
        config["filters"]["property_types"] = []
        config["filters"]["okrugs"] = []
        save_json(CONFIG_PATH, config)
        send_telegram_message("Бюджет, тип жилья и округ сброшены.")
        return

    parts = text.strip().split(maxsplit=1)
    cmd = parts[0].lower().split("@")[0]  # убираем "@имя_бота", если Telegram его добавил
    arg = parts[1].strip() if len(parts) > 1 else ""

    if cmd == "/help" or cmd == "/start":
        send_telegram_message(HELP_TEXT, reply_markup=MAIN_REPLY_KEYBOARD)
        return

    if cmd == "/menu":
        show_filters_menu()
        return

    if cmd == "/price":
        nums = arg.split()
        if len(nums) != 2 or not all(n.isdigit() for n in nums):
            send_telegram_message("Формат: /price мин макс, например /price 0 50000")
            return
        config["filters"]["price_min"] = int(nums[0])
        config["filters"]["price_max"] = int(nums[1])
        save_json(CONFIG_PATH, config)
        send_telegram_message(f"Готово: цена от {nums[0]} до {nums[1]} руб")
        return

    if cmd == "/metro":
        if not arg.isdigit():
            send_telegram_message("Формат: /metro минуты, например /metro 20")
            return
        config["filters"]["metro_max_minutes"] = int(arg)
        save_json(CONFIG_PATH, config)
        send_telegram_message(f"Готово: метро до {arg} мин. пешком")
        return

    if cmd == "/rooms":
        if arg.strip() == "0":
            config["filters"]["rooms"] = []
            save_json(CONFIG_PATH, config)
            send_telegram_message("Готово: фильтр по числу комнат сброшен (подходит любое)")
            return
        nums = [n.strip() for n in arg.split(",") if n.strip()]
        if not nums or not all(n.isdigit() for n in nums):
            send_telegram_message("Формат: /rooms 1,2 (или /rooms 0, чтобы сбросить)")
            return
        config["filters"]["rooms"] = [int(n) for n in nums]
        save_json(CONFIG_PATH, config)
        send_telegram_message("Готово: подходящее число комнат — " + ", ".join(nums))
        return

    if cmd == "/districts":
        if arg.strip() == "0":
            config["filters"]["districts"] = []
            save_json(CONFIG_PATH, config)
            send_telegram_message("Готово: фильтр по районам сброшен (подходит любой)")
            return
        if not arg:
            send_telegram_message("Формат: /districts район1,район2 (или /districts 0, чтобы сбросить)")
            return
        districts = [d.strip() for d in arg.split(",") if d.strip()]
        config["filters"]["districts"] = districts
        save_json(CONFIG_PATH, config)
        send_telegram_message("Готово: районы — " + ", ".join(districts))
        return

    if cmd == "/keywords":
        if not arg:
            send_telegram_message("Формат: /keywords слово1,слово2,...")
            return
        words = [w.strip() for w in arg.split(",") if w.strip()]
        config["filters"]["keywords_include"] = words
        save_json(CONFIG_PATH, config)
        send_telegram_message("Готово: ключевые слова — " + ", ".join(words))
        return

    if cmd == "/exclude":
        if not arg:
            send_telegram_message("Формат: /exclude слово1,слово2,...")
            return
        words = [w.strip() for w in arg.split(",") if w.strip()]
        config["filters"]["keywords_exclude"] = words
        save_json(CONFIG_PATH, config)
        send_telegram_message("Готово: слова-исключения — " + ", ".join(words))
        return

    if cmd == "/addchannel":
        if not arg:
            send_telegram_message("Формат: /addchannel имя_канала")
            return
        channel = arg.lstrip("@").strip()
        if channel not in config["channels"]:
            config["channels"].append(channel)
            save_json(CONFIG_PATH, config)
        send_telegram_message(f"Готово: канал {channel} добавлен")
        return

    if cmd == "/removechannel":
        if not arg:
            send_telegram_message("Формат: /removechannel имя_канала")
            return
        channel = arg.lstrip("@").strip()
        if channel in config["channels"]:
            config["channels"].remove(channel)
            save_json(CONFIG_PATH, config)
            send_telegram_message(f"Готово: канал {channel} убран")
        else:
            send_telegram_message(f"Канал {channel} не найден в списке")
        return

    if cmd == "/channels":
        send_telegram_message("Текущие каналы:\n" + "\n".join(config["channels"]))
        return

    if cmd == "/filters":
        f = config["filters"]
        if f.get("price_ranges"):
            price_line = ", ".join(_budget_label(lo, hi) for lo, hi in f["price_ranges"])
        else:
            price_line = f"{f['price_min']}–{f['price_max']} руб"
        types_line = ", ".join(f.get("property_types") or []) or "любой"
        okrugs_line = ", ".join(f.get("okrugs") or []) or "любой"
        reply = (
            "Текущие фильтры:\n\n"
            f"Ключевые слова: {', '.join(f['keywords_include'])}\n"
            f"Исключения: {', '.join(f['keywords_exclude'])}\n"
            f"Цена: {price_line}\n"
            f"Тип жилья: {types_line}\n"
            f"Округ: {okrugs_line}\n"
            f"Метро: до {f.get('metro_max_minutes', '—')} мин. пешком\n"
            f"Районы: {', '.join(f['districts']) or 'любые'}"
        )
        send_telegram_message(reply)
        return

    # неизвестная команда/обычное сообщение не по теме — молча игнорируем


def handle_update(upd):
    cq = upd.get("callback_query")
    if cq:
        handle_callback_query(cq)
        return

    msg = upd.get("message")
    if not msg:
        return
    chat_id = str(msg["chat"]["id"])
    if chat_id != str(MY_CHAT_ID):
        return  # игнорируем сообщения не из твоего чата

    # временный помощник: если прислали/переслали кастомный эмодзи (нужно
    # для веток метро) — сохраняем его custom_emoji_id в файл (раньше id
    # только отправлялся в чат и терялся, если не переписать вручную) и
    # отвечаем тем же списком. Если рядом с эмодзи есть текст (например
    # "10" или "Люблинско-Дмитровская") — сохраняем и его как подпись
    entities = (msg.get("entities") or []) + (msg.get("caption_entities") or [])
    custom_emojis = [ent for ent in entities if ent.get("type") == "custom_emoji"]
    # калибровочный помощник для подбора custom_emoji_id веток метро — не
    # нужен в обычной работе бота (все линии уже откалиброваны в
    # METRO_LINE_EMOJI_ID), включается явно переменной окружения, чтобы
    # случайный кастомный эмодзи в чужом сообщении не перехватывал его
    # молча вместо обычной обработки текста/команды
    if custom_emojis and os.environ.get("ROOM_BOT_CAPTURE_EMOJI"):
        raw = msg.get("text") or msg.get("caption") or ""
        # offset/length в апдейте — в UTF-16 code units, не в питоновских
        # символах, поэтому режем по utf-16, а не по raw[start:end]
        utf16 = raw.encode("utf-16-le")

        covered = sorted(
            (ent["offset"] * 2, (ent["offset"] + ent["length"]) * 2)
            for ent in custom_emojis
        )
        label_parts = []
        pos = 0
        for start, end in covered:
            label_parts.append(utf16[pos:start])
            pos = end
        label_parts.append(utf16[pos:])
        label = b"".join(label_parts).decode("utf-16-le", errors="ignore").strip()

        ts = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        lines = []
        log_lines = []
        for ent in custom_emojis:
            start = ent["offset"] * 2
            end = start + ent["length"] * 2
            char = utf16[start:end].decode("utf-16-le")
            lines.append(f"{char}  id={ent['custom_emoji_id']}")
            log_lines.append(
                f"[{ts}] id={ent['custom_emoji_id']} char={char!r} label={label!r}"
            )
        try:
            with open(EMOJI_LOG_PATH, "a", encoding="utf-8") as f:
                f.write("\n".join(log_lines) + "\n")
        except OSError:
            pass

        reply = f"Сохранил {len(custom_emojis)} шт. в emoji_ids.log:\n" + "\n".join(lines)
        if label:
            reply += f"\nПодпись рядом: {label}"
        send_telegram_message(reply)
        return

    if "text" not in msg:
        return

    text = msg["text"].strip()
    if text.startswith("/") or text in (FILTERS_MENU_BUTTON, FILTERS_RESET_BUTTON):
        handle_command(text)


def _process_update_batch(updates):
    # общая логика для одноразового опроса (process_commands) и непрерывного
    # слушателя (listen_loop) — раньше была продублирована в обоих местах
    if not updates:
        return
    max_update_id = state.get("last_update_id", 0)
    for upd in updates:
        max_update_id = max(max_update_id, upd["update_id"])
        handle_update(upd)
    save_state(last_update_id=max_update_id)


def process_commands():
    _process_update_batch(get_telegram_updates())


def listen_loop():
    # непрерывный long-polling: держит соединение с Telegram открытым до
    # 25 секунд в ожидании нового апдейта — как только он приходит, кнопка/
    # команда обрабатывается сразу же, без задержки в 15 минут/1 минуту,
    # свойственной запуску через Планировщик
    log("Слушатель команд запущен")
    while True:
        try:
            started = time.monotonic()
            updates = get_telegram_updates(poll_timeout=25)
            if updates:
                _process_update_batch(updates)
            elif time.monotonic() - started < 3:
                # get_telegram_updates сама логирует ошибку и возвращает []
                # вместо исключения — без этой паузы обрыв сети (DNS и т.п.)
                # уходит в цикл переподключений без задержки и заваливает лог
                time.sleep(5)
        except Exception as e:
            log(f"Ошибка в цикле прослушивания: {e}")
            time.sleep(5)


