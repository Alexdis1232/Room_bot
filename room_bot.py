def load_json(path, default):
    if os.path.exists(path):
        with open(path, "r", encoding="utf-8") as f:
            return json.load(f)
    return default


def save_json(path, data):
    with open(path, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


def _lock_file(f):
    if os.name == "nt":
        f.seek(0)
        msvcrt.locking(f.fileno(), msvcrt.LK_LOCK, 1)
    else:
        fcntl.flock(f.fileno(), fcntl.LOCK_EX)


def _unlock_file(f):
    if os.name == "nt":
        f.seek(0)
        msvcrt.locking(f.fileno(), msvcrt.LK_UNLCK, 1)
    else:
        fcntl.flock(f.fileno(), fcntl.LOCK_UN)


def save_state(**changed):
    # RoomBot (плановый скан каналов) и RoomBotListener (непрерывный
    # слушатель команд/кнопок) — два независимых процесса, каждый со своей
    # копией state в памяти с момента своего запуска. Если оба просто
    # перезаписывают state.json целиком, тот, что сохраняет позже, стирает
    # изменения другого — например, слушатель мог откатить last_ids/
    # sent_post_ids, которые скан только что обновил. Поэтому перед записью
    # всегда перечитываем ФАКТИЧЕСКОЕ содержимое файла с диска и накладываем
    # поверх только те поля, которые реально изменил именно этот вызов; сама
    # запись — под файловой блокировкой, чтобы два процесса не считали и не
    # переписали файл одновременно
    global state
    with open(STATE_LOCK_PATH, "a+b") as lock_file:
        _lock_file(lock_file)
        try:
            fresh = load_json(STATE_PATH, {"last_ids": {}})
            fresh.update(changed)
            save_json(STATE_PATH, fresh)
            state = fresh
        finally:
            _unlock_file(lock_file)
    return state


