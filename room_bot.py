# число либо сгруппировано по 3 цифры через пробел/точку ("55.000", "45 000"),
# либо идёт слитно без разделителей ("40000"); НЕ допускаем произвольные
# пробелы/точки внутри цифр без строгой группировки — иначе regex может
# "перескочить" через границу предложения и склеить номер дома с ценой
_PRICE_NUM = r"(?:\d{1,3}(?:[ .]\d{3})+|\d{3,9})"
PRICE_RE = re.compile(r"(" + _PRICE_NUM + r")\s?(?:руб|₽|р\.)", re.IGNORECASE)
# "цена"/"оплата"/"плата" по всем падежам ("по цене", "оплату", "платы"), а
# не только именительный — раньше "По цене: 28к" не ловилось, потому что
# слово стояло в предложном падеже ("цене"), а не "цена". \b на конце —
# чтобы не задеть другие слова с тем же началом ("центр", "платье")
_PRICE_KEYWORD = r"(?:о)?плат(?:а|у|е|ы|ой)\b|цен(?:а|е|у|ы|ой)\b"
# запасной вариант: число рядом со словами "плата/цена/стоимость" даже без
# явной валютной пометки — многие объявления специально её опускают или
# коверкают ("55.000ку"), чтобы обойти простые фильтры
PRICE_CONTEXT_RE = re.compile(
    r"(?:арендн\w*\s*плат\w*|аренда\w*|" + _PRICE_KEYWORD + r"|стоимост\w*)\D{0,10}(" + _PRICE_NUM + r")",
    re.IGNORECASE,
)
# число сразу перед "/мес"/"месяц" — тоже цена, даже без "руб"/"₽" и без
# слова "цена/плата" рядом (например "💰 95.500 месяц"). _PRICE_NUM требует
# минимум 3 цифры, поэтому срок аренды вроде "6 месяцев" сюда не попадёт
PRICE_MONTH_RE = re.compile(r"(" + _PRICE_NUM + r")\s?/?\s?(?:мес\.?\b|месяц\w*)", re.IGNORECASE)
# сокращённая запись тысяч ("Оплата 45+ счётчики" = 45 тысяч + коммуналка) —
# двузначное число сразу после "оплата/цена/плата", с явным сигналом
# сокращения ("+", "тыс", "к") сразу за ним, иначе слишком легко ошибиться
PRICE_SHORTHAND_RE = re.compile(
    r"(?:" + _PRICE_KEYWORD + r")\D{0,5}(\d{2,3})\s*(?:\+|тыс\w*|к\b)",
    re.IGNORECASE,
)
DEPOSIT_RE = re.compile(r"залог\w*|депозит\w*", re.IGNORECASE)
COMMISSION_RE = re.compile(r"комисси\w*", re.IGNORECASE)
# отдельные мелкие ежемесячные платежи (интернет и т.п.) со своим "руб/₽"
# рядом — их сумма меньше аренды и раньше могла победить как "минимальная"
# цена в extract_price ("Интернет — 450 ₽ в месяц" вместо реальных 46 000)
INTERNET_RE = re.compile(r"интернет\w*", re.IGNORECASE)
# "коммунал..." — целое слово (коммуналка/коммунальные и т.п.), либо
# "ЖКХ" (жилищно-коммунальное хозяйство — частый синоним в объявлениях),
# либо сокращение "к.у."/"ку", которое пишут вплотную после суммы
# ("55.000ку") — поэтому его ловим только сразу после цифры, а не "\bку\b"
# где угодно (иначе задело бы "девушку", "мышку" и любое другое слово на "-ку")
UTILITIES_RE = re.compile(
    r"коммунал\w*"
    r"|\bжкх\b"
    r"|(?<=\d)\s*к\.?\s*у\.?\b",
    re.IGNORECASE,
)
# "коммунал..."/"ЖКХ" — используется отдельно, чтобы искать рядом с ним
# КОНКРЕТНУЮ сумму (в отличие от UTILITIES_RE это не годится для "55.000ку",
# там суффикс — часть самой цены, а не отдельная сумма)
UTIL_KEYWORD_RE = re.compile(r"коммунал\w*|\bжкх\b", re.IGNORECASE)
ROOMS_RE = re.compile(r"(\d)[\s\-]*(?:к\b|комн)", re.IGNORECASE)
# "комната"/"комнату"/"комнаты" — существительное (сдаётся комната), в
# отличие от "комнатная" — прилагательное в "N-комнатная квартира"
# (описание квартиры целиком, не то, что сдаётся). Также исключаем составные
# слова "ванная комната"/"детская комната" (и их падежные формы) — это
# описание планировки студии/квартиры, а не признак того, что сдаётся именно
# комната (раньше любое упоминание "Ванная комната" в списке удобств
# перекрывало реальный тип "Студия" из заголовка объявления)
ROOM_WORD_RE = re.compile(
    r"(?<!ванн(?:ая|ую|ой)\s)(?<!детск(?:ая|ую|ой)\s)\bкомнат[ауы]\b",
    re.IGNORECASE,
)
# "м" как сокращение метро часто пишут без точки (структурированные объявления
# вида "м Марксистская"); \bм\.?(?=\s) требует отдельное слово из одной буквы,
# чтобы не сработать на "дом", "самолёт" и т.п.
# группы: (минуты, способ) для варианта "N мин ... метро",
# (минуты, способ) для варианта "метро ... N мин ..." — способ передвижения
# ("пешком"/"на транспорте"/"на машине") сохраняем, а не всегда пишем "пешком"
METRO_RE = re.compile(
    r"(?:(\d{1,2})\s*мин[а-я]*\s*(пешком|на транспорте|на машине|на авто\w*)?\s*(?:до|от)?\s*(?:метро|\bм\.?(?=\s)))"
    r"|(?:(?:метро|\bм\.?(?=\s))[^\d]{0,20}?(\d{1,2})\s*мин[а-я]*\s*(пешком|на транспорте|на машине|на авто\w*)?)",
    re.IGNORECASE,
)


def _normalize_transport_mode(mode):
    if not mode:
        return "пешком"
    mode = mode.lower()
    if "трансп" in mode:
        return "на транспорте"
    if "машин" in mode or "авто" in mode:
        return "на машине"
    return "пешком"


def _price_to_int(raw):
    # убираем пробелы и точки-разделители тысяч ("55.000" -> "55000")
    cleaned = re.sub(r"[\s.]", "", raw)
    try:
        return int(cleaned)
    except ValueError:
        # на случай совсем неожиданного формата — просто пропускаем
        return None


_NEGATION_RE = re.compile(r"\b(?:без|включ\w*)\b", re.IGNORECASE)


def _is_negated(text, match_start, lookback=30):
    # "без коммуналки и залога", "коммуналка включена" — значит этого пункта
    # в объявлении нет / он уже внутри цены, а не отдельная сумма. Окно
    # побольше — чтобы захватить "без" и в конструкции "без X и Y", где Y
    # может стоять на 20+ символов дальше самого "без"
    start = max(0, match_start - lookback)
    prefix = text[start:match_start]
    # но если внутри этого окна есть конец предложения — "без" перед ним
    # относится к ДРУГОЙ фразе ("Без комиссии. Залог возвращается." — тут
    # "без" про комиссию, а не про залог), поэтому обрезаем по границе
    boundaries = list(_SENTENCE_BOUNDARY_RE.finditer(prefix))
    if boundaries:
        prefix = prefix[boundaries[-1].end():]
    return bool(_NEGATION_RE.search(prefix))


def _keyword_present(text, keyword_re):
    return any(not _is_negated(text, m.start()) for m in keyword_re.finditer(text))


# конец предложения/пункта списка — точка (не являющаяся разделителем тысяч
# внутри числа, у "3.600" она стоит вплотную между цифрами) или запятая —
# _PRICE_NUM запятую как разделитель тысяч никогда не использует, так что
# её можно считать границей безусловно. Перенос строки — тоже граница: в
# объявлениях каждое поле обычно на своей строке ("...КУ включены\nЗалог:
# 5к..."), и "включены" из строки про коммуналку не должно считаться
# отрицанием для залога строкой ниже
_SENTENCE_BOUNDARY_RE = re.compile(r"(?<!\d)\.(?!\d)|,|\n")
# разделитель "цена + отдельная сумма" — символ "+" или слово "плюс"
_JOIN_SEPARATOR_RE = re.compile(r"\+|плюс", re.IGNORECASE)


def _find_amount_near_keyword(text, keyword_re, window=20):
    # ищет ЧИСЛО рядом с ключевым словом — сначала после него, потом перед
    # ним, но НЕ дальше границы предложения: иначе легко зацепить число из
    # другого предложения — например саму цену аренды в "90.000₽ +
    # коммунальные услуги" (перед "коммунальные" нет точки, но и числа там
    # для "коммунальные" тоже нет — оно относится к предыдущей части через "+")
    num_re = re.compile(_PRICE_NUM)
    for km in keyword_re.finditer(text):
        if _is_negated(text, km.start()):
            continue

        fwd_end = min(len(text), km.end() + window)
        boundary = _SENTENCE_BOUNDARY_RE.search(text, km.end(), fwd_end)
        if boundary:
            fwd_end = boundary.start()
        after = num_re.search(text, km.end(), fwd_end)
        # число сразу после знака "%" — это доля ("Депозит 100%"), а не
        # сумма в рублях, такое не считаем
        if after and text[after.end():after.end() + 1] != "%":
            return _price_to_int(after.group(0)), after.span()

        # число перед словом берём только если между ним и словом нет
        # точки/"+"/"плюс" — если есть, это, скорее всего, отдельная сумма
        # из другой части фразы (например основная цена перед "+ коммуналка"
        # или "N руб плюс коммунальные")
        back_start = max(0, km.start() - window)
        boundaries = list(_SENTENCE_BOUNDARY_RE.finditer(text, back_start, km.start()))
        if boundaries:
            back_start = boundaries[-1].end()
        before_matches = list(num_re.finditer(text, back_start, km.start()))
        if before_matches:
            bm = before_matches[-1]
            between = text[bm.end():km.start()]
            if "." not in between and not _JOIN_SEPARATOR_RE.search(between):
                return _price_to_int(bm.group(0)), bm.span()
    return None


def _span_overlaps_any(span, spans):
    return any(span[0] < e and span[1] > s for s, e in spans)


def _price_exclusion_spans(text):
    # суммы коммуналки/залога не должны попадать в основную цену аренды —
    # раньше "70 000 + 3 600 коммунальные" отдавало 3 600 как цену, потому
    # что бралось минимальное из всех найденных чисел с валютой
    spans = []
    for keyword_re in (DEPOSIT_RE, UTIL_KEYWORD_RE, COMMISSION_RE, INTERNET_RE):
        found = _find_amount_near_keyword(text, keyword_re)
        if found:
            spans.append(found[1])
    return spans


def _is_range_upper_bound(text, num_start):
    # "3 000–4 000 ₽ в месяц" (типично для оценки коммуналки "от и до") —
    # число сразу после тире, перед которым тоже цифра, это верхняя граница
    # диапазона, а не отдельная цена сама по себе; раньше такое число могло
    # выигрывать как "минимальное" среди найденных цен, забивая настоящую
    # аренду, если рядом не было опознано ключевое слово-исключение
    prefix = text[max(0, num_start - 10):num_start].rstrip()
    if not prefix or prefix[-1] not in "-–—":
        return False
    before_dash = prefix[:-1].rstrip()
    return bool(before_dash) and before_dash[-1].isdigit()


def extract_price(text):
    exclude_spans = _price_exclusion_spans(text)

    nums = []
    for m in PRICE_RE.finditer(text):
        if _span_overlaps_any(m.span(1), exclude_spans):
            continue
        if _is_range_upper_bound(text, m.start(1)):
            continue
        val = _price_to_int(m.group(1))
        if val is not None:
            nums.append(val)
    if nums:
        return min(nums)

    for m in PRICE_CONTEXT_RE.finditer(text):
        if _span_overlaps_any(m.span(1), exclude_spans):
            continue
        val = _price_to_int(m.group(1))
        if val is not None:
            return val

    for m in PRICE_MONTH_RE.finditer(text):
        if _span_overlaps_any(m.span(1), exclude_spans):
            continue
        val = _price_to_int(m.group(1))
        if val is not None:
            return val

    for m in PRICE_SHORTHAND_RE.finditer(text):
        if _span_overlaps_any(m.span(1), exclude_spans):
            continue
        val = _price_to_int(m.group(1))
        if val is not None:
            return val * 1000

    return None


def _has_negated_only(text, keyword_re):
    # True, если слово встречается в тексте, но КАЖДОЕ упоминание — с
    # отрицанием ("без залога") — тогда это тоже стоит показать явно, а не
    # молча пропустить, как будто про это вообще ничего не сказано
    matches = list(keyword_re.finditer(text))
    if not matches:
        return False
    return all(_is_negated(text, m.start()) for m in matches)


def extract_price_extras(text):
    # порядок фиксированный: комиссия, коммунальные услуги, залог — с
    # конкретной суммой, если она указана рядом со словом; если явно
    # написано "без X" — тоже показываем (это тоже полезная информация,
    # а не то же самое, что если про X вообще ничего не сказано)
    extras = []
    items = (
        (COMMISSION_RE, COMMISSION_RE, "комиссия", "без комиссии"),
        (UTILITIES_RE, UTIL_KEYWORD_RE, "коммунальные услуги", "без коммунальных услуг"),
        (DEPOSIT_RE, DEPOSIT_RE, "залог", "без залога"),
    )
    for presence_re, amount_re, label, negative_label in items:
        found = _find_amount_near_keyword(text, amount_re)
        if found:
            amount = f"{found[0]:,} руб".replace(",", " ")
            extras.append(f"{amount} {label}")
        elif _keyword_present(text, presence_re):
            extras.append(label)
        elif _has_negated_only(text, presence_re):
            extras.append(negative_label)

    return extras


def extract_rooms(text):
    m = ROOMS_RE.search(text)
    if not m:
        return None
    return int(m.group(1))


def extract_metro_minutes_and_mode(text):
    m = METRO_RE.search(text)
    if not m:
        return None, None
    minutes = m.group(1) or m.group(3)
    mode = m.group(2) or m.group(4)
    return int(minutes), mode


def extract_metro_minutes(text):
    minutes, _ = extract_metro_minutes_and_mode(text)
    return minutes


