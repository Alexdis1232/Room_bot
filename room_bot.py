# отдельные предметы обстановки (кровать, диван и т.п.) или просто слово
# "мебель" — по фото сказать, меблирована ли квартира, бот не может, поэтому
# ориентируется на то, что перечислено в тексте. Если нашлось хоть что-то
# одно (и не отрицается, "без мебели") — в удобства добавляется одна строка
# "базовая мебель" первым пунктом, а не попытка перечислить каждый предмет
BASIC_FURNITURE_RE = re.compile(
    r"\bмебель\w*\b|\bкроват\w*\b|\bдиван\w*\b|\bкомод\w*\b"
    r"|\bстол(?!иц|ич)\w*\b|\bстул\w*\b",
    re.IGNORECASE,
)
# "шкаф" отдельно от общего списка — не считаем платяным шкафом/гардеробом,
# если это часть "духовой шкаф" (кухонная техника, см. _OVEN_PATTERN)
_OVEN_RE = re.compile(_OVEN_PATTERN, re.IGNORECASE)
WARDROBE_RE = re.compile(r"\bшкаф\w*\b", re.IGNORECASE)


def _has_basic_furniture(text):
    if _keyword_present(text, BASIC_FURNITURE_RE):
        return True
    oven_spans = [m.span() for m in _OVEN_RE.finditer(text)]
    for m in WARDROBE_RE.finditer(text):
        if _span_overlaps_any(m.span(), oven_spans):
            continue
        if not _is_negated(text, m.start()):
            return True
    return False


def extract_amenities(text):
    # мебель и техника внутри квартиры — отдельно от инфраструктуры вокруг
    lower = text.lower()
    found = []
    seen = set()
    if _has_basic_furniture(text):
        found.append("базовая мебель")
        seen.add("базовая мебель")
    for pattern, label in AMENITY_KEYWORDS:
        if label in seen:
            continue
        if re.search(pattern, lower, re.IGNORECASE):
            found.append(label)
            seen.add(label)
    return found


def extract_infrastructure(text):
    # всё, что снаружи квартиры: парки/магазины/сады рядом + описание ЖК.
    # Само название ЖК сюда не попадает — оно теперь всегда идёт в адрес
    # (см. extract_address), чтобы не дублироваться в двух местах
    lower = text.lower()
    found = []
    seen = set()

    for pattern, label in ZHK_DESCRIPTION_KEYWORDS + INFRA_KEYWORDS:
        if label in seen:
            continue
        if re.search(pattern, lower, re.IGNORECASE):
            found.append(label)
            seen.add(label)

    # магазины/сети — реальным названием из текста, а не обобщённой фразой
    shop_names = []
    for m in SHOP_NAME_RE.finditer(text):
        name = m.group(0).strip()
        key = name.lower()
        if key not in seen:
            seen.add(key)
            shop_names.append(name)
    if shop_names:
        found.extend(shop_names)
    elif GENERIC_SHOP_RE.search(text) and "магазины рядом" not in seen:
        found.append("магазины рядом")
        seen.add("магазины рядом")

    return found


