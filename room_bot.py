def _flex_word(word):
    # у русских слов склонение/спряжение меняет обычно последние 1-3 буквы —
    # отбрасываем последние 2 и разрешаем вместо них любое окончание длиной
    # 0-4 буквы, чтобы ловить падежные формы КАЖДОГО слова в названии
    # ("Чистые пруды" -> "Чистыми прудами", "Профсоюзная" -> "Профсоюзной").
    # Только для слов подлиннее — короткий корень (например "Пан" от
    # "Панки") слишком общий и ложно цепляет случайные слова вроде
    # "панель"; для коротких имён (≤6 букв) — точное совпадение
    if len(word) > 6:
        return re.escape(word[:-2]) + r"[а-яёА-ЯЁ]{0,4}"
    return re.escape(word)


def _station_search_pattern(name):
    # дефис в названии ("Китай-город") тоже делаем гибким — в объявлениях
    # его часто заменяют пробелом ("Китай Город") или вовсе опускают
    words = re.split(r"[\s\-]+", name)
    body = r"[\s\-]+".join(_flex_word(w) for w in words)
    return re.compile(r"(?<![а-яёА-ЯЁ])" + body + r"(?![а-яёА-ЯЁ])", re.IGNORECASE)


# сортируем по длине названия по убыванию — чтобы длинные, более конкретные
# названия ("Юго-Западная") проверялись раньше более коротких совпадений
_STATION_PATTERNS = sorted(
    ((name, _station_search_pattern(name)) for name in METRO_STATIONS),
    key=lambda pair: -len(pair[0]),
)


def find_known_station(text):
    # резервный поиск станции по справочнику — используется только когда
    # METRO_STATION_RE не нашёл станцию рядом со словом "метро"/"м.".
    # Если в тексте перечислено несколько станций ("рядом Китай-город,
    # Лубянка, Театральная и Кузнецкий мост") — берём ту, что упомянута
    # РАНЬШЕ по тексту, а не самое длинное совпадающее название
    best = None
    for name, pattern in _STATION_PATTERNS:
        m = pattern.search(text)
        if m and (best is None or m.start() < best[0]):
            best = (m.start(), name)
    return best[1] if best else None


# короткие сокращения ("ул", "ш", "пер", "наб") часто пишут без точки —
# \b...(?=\s) требует отдельное слово, чтобы не задеть "стул", "шапка" и т.п.
ADDRESS_TYPE = (
    # после сокращения перед пробелом часто ещё стоит запятая ("Волоколамское
    # ш., 24к1") — раньше (?=\s) требовал пробел сразу после точки и такие
    # адреса не находились вообще
    r"(?:\bул\.?(?=,?\s)|улица|проспект|пр-?т|переулок|\bпер\.?(?=,?\s)|шоссе|"
    r"\bш\.?(?=,?\s)|набережная|\bнаб\.?(?=,?\s)|бульвар|б-р)"
)

ADDRESS_RE = re.compile(
    # необязательное слово перед типом улицы — многие названия ставят его
    # раньше типа, например "Пролетарский пр-т", "Кутузовский проспект"
    r"((?:[А-ЯЁ][а-яёА-ЯЁ\-]+\s)?" + ADDRESS_TYPE + r"\s?[^\n]{2,60})",
    re.IGNORECASE,
)


def extract_property_type(text):
    lower = text.lower()

    if "евродвушк" in lower:
        return "Евродвушка"
    if "евротрешк" in lower or "евротрёшк" in lower:
        return "Евротрешка"
    if "евростуди" in lower:
        return "Евростудия"
    if "ищу сосед" in lower:
        return "Ищу соседку/соседа"

    # "комната"/"комнату"/"комнаты" отдельным словом значит, что сдаётся
    # именно комната — даже если дальше по тексту упоминается описание всей
    # квартиры вроде "2-комнатная квартира" (у него другое окончание,
    # ROOM_WORD_RE его не ловит, поэтому проверяем это раньше подсчёта комнат)
    if ROOM_WORD_RE.search(text):
        return "Комната"

    rooms = extract_rooms(text)
    if rooms:
        return f"{rooms}-к квартира"

    if "однушк" in lower:
        return "1-к квартира"
    if "студи" in lower:
        return "Студия"

    return "Не определено"


