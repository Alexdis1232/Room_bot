AREA_RE = re.compile(r"(\d{1,3}(?:[.,]\d{1,2})?)\s*(?:кв\.?\s*м\.?|м²|m2)", re.IGNORECASE)
# сокращённая запись без "кв."/"²" — просто число и слитное "м" ("19,6м у
# метро"). (?!\.) — чтобы не задеть "15м. Марксистская" (это "м." метро, а
# не площадь), \b после — чтобы не поймать начало другого слова на "м"
AREA_SHORTHAND_RE = re.compile(r"(\d{1,3}(?:[.,]\d{1,2})?)\s?м\b(?!\.)", re.IGNORECASE)

# два распространённых формата: "12 этаж из 17" и слитное "8/15эт"
FLOOR_RE = re.compile(r"(\d{1,2})[\-\s]*(?:й\s*)?этаж(?:[а-я]*\s*из\s*(\d{1,3}))?", re.IGNORECASE)
# "эт" сокращённо ("8/15эт") ИЛИ полным словом ("3/8 этаж") — второе не
# ловится FLOOR_RE, т.к. тот берёт только число сразу перед "этаж" и в
# "3/8 этаж" выхватывает одно "8", теряя "3/"
FLOOR_SLASH_RE = re.compile(r"\b(\d{1,2})\s*/\s*(\d{1,3})\s*эт[а-я]*\.?\b", re.IGNORECASE)


def extract_floor(text):
    # сначала более специфичный формат "N/M" — иначе FLOOR_RE в "3/8 этаж"
    # выхватит только "8 этаж", потеряв "3/"
    m = FLOOR_SLASH_RE.search(text)
    if m:
        return f"{m.group(1)} из {m.group(2)}"

    m = FLOOR_RE.search(text)
    if m:
        floor, total = m.group(1), m.group(2)
        return f"{floor} из {total}" if total else floor

    return None


def extract_area(text):
    m = AREA_RE.search(text)
    if not m:
        m = AREA_SHORTHAND_RE.search(text)
    if not m:
        return None
    return m.group(1).replace(".", ",")


