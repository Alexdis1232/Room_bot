LOG_MAX_BYTES = 1_000_000


def log(msg):
    # Планировщик запускает скрипт через pythonw.exe, у которого нет консоли
    # и sys.stdout/stderr равны None — обычный print() в такой среде падает
    # с исключением и обрывает скрипт. Поэтому основной канал — файл; вывод
    # в stdout — best-effort сверху (на Linux/systemd он есть всегда и его
    # удобно смотреть через journalctl).
    line = f"[{datetime.now():%Y-%m-%d %H:%M:%S}] {msg}\n"
    try:
        print(line, end="")
    except Exception:
        pass
    try:
        # если файл разросся (например, из-за цикла ошибок) — обрезаем,
        # оставляя только недавний хвост, чтобы лог не рос бесконечно
        if os.path.exists(LOG_PATH) and os.path.getsize(LOG_PATH) > LOG_MAX_BYTES:
            with open(LOG_PATH, "rb") as f:
                f.seek(-LOG_MAX_BYTES // 2, os.SEEK_END)
                tail = f.read()
            with open(LOG_PATH, "wb") as f:
                f.write(tail)
        with open(LOG_PATH, "a", encoding="utf-8") as f:
            f.write(line)
    except OSError:
        pass


