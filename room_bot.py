def build_map_link(address, metro_station):
    # ссылка-поиск Яндекс.Карт — работает без API-ключа, просто открывает
    # карту по текстовому запросу (адрес точнее, станция метро — запасной
    # вариант, если адреса в объявлении нет)
    query = f"Москва, {address}" if address else (f"Москва, метро {metro_station}" if metro_station else None)
    if not query:
        return None
    return f"https://yandex.ru/maps/?text={quote(query)}"


# Telegram HTML не поддерживает цвет текста напрямую — <blockquote> (полоска
# сбоку + фон, как у цитаты) вместе с жирным шрифтом и эмодзи ближайший
# доступный аналог "выделить красным" для предупреждения о мошенниках
SCAM_WARNING_EMOJI_ID = "5447644880824181073"
SCAM_WARNING_HTML = (
    f'<blockquote><tg-emoji emoji-id="{SCAM_WARNING_EMOJI_ID}">⚠️</tg-emoji> '
    "<b>Будьте бдительны! Не переводите никому деньги по "
    "предоплате!</b></blockquote>"
)


def format_post_message(p):
    property_type = extract_property_type(p["text"])
    area = extract_area(p["text"])
    metro = extract_metro_info(p["text"])
    metro_station = extract_metro_station(p["text"])
    floor = extract_floor(p["text"])
    address = extract_address(p["text"])
    price = extract_price(p["text"])
    contacts = extract_contacts(p["text"])

    type_label = f"{property_type}, {area} м²" if area else property_type
    if price:
        price_label = f"{price:,} руб".replace(",", " ")
    elif re.search(r"\bбесплатно\b", p["text"], re.IGNORECASE):
        price_label = "Бесплатно"
    else:
        price_label = "не указана"
    extras = extract_price_extras(p["text"])
    if extras:
        price_label += " + " + " + ".join(extras)

    # экранируем всё, что взято из свободного текста поста,
    # чтобы случайные символы <, >, & не сломали HTML-разметку
    e = html.escape

    # цветной кружок ветки метро вместо обычного 🚇, когда станция и её
    # линия распознаны и для линии уже есть кастомный эмодзи
    metro_icon = metro_line_icon_html(metro_station) if metro_station else "🚇"

    # ссылка на карту (без API-ключа, обычная ссылка-поиск Яндекс.Карт) —
    # отдельной подписью "на карте" рядом, сам адрес/станцию ссылкой не
    # выделяем; вешаем на адрес, если он есть, иначе на станцию метро
    map_link = build_map_link(address, metro_station)
    address_value = e(address) if address else "не указан"
    metro_value = e(metro) if metro else "не указано"
    map_suffix = f' (<a href="{e(map_link)}">на карте</a>)' if map_link else ""
    if map_link and address:
        address_value += map_suffix
    elif map_link and metro:
        metro_value += map_suffix

    blocks = [
        f"🏠 Сдаётся: <b>{e(type_label)}</b>",
    ]
    if floor:
        # этаж есть не в каждом объявлении — показываем строкой, только
        # когда он реально нашёлся в тексте
        blocks.append(f"🏢 Этаж: <b>{e(floor)}</b>")

    blocks += [
        f"{metro_icon} Метро: <b>{metro_value}</b>",
        f"📍 Адрес: <b>{address_value}</b>",
        f"💰 Цена: {e(price_label)}",
    ]

    # мебель/техника и инфраструктура — двумя отдельными блоками, только
    # если реально что-то нашлось; без эмодзи в заголовке, текст с новой
    # строки, каждый пункт — с большой буквы
    amenities = extract_amenities(p["text"])
    if amenities:
        capitalized = [a[0].upper() + a[1:] if a else a for a in amenities]
        blocks.append(f"Что входит:\n{e(', '.join(capitalized))}")

    infrastructure = extract_infrastructure(p["text"])
    if infrastructure:
        capitalized = [a[0].upper() + a[1:] if a else a for a in infrastructure]
        blocks.append(f"Инфраструктура:\n{e(', '.join(capitalized))}")

    blocks += [
        f"📞 Контакты: {e(contacts or 'не указаны')}",
        f"🔗 Подробнее: {e(p['link'])}",
        SCAM_WARNING_HTML,
    ]
    return "\n\n".join(blocks)


# у sendPhoto подпись (caption) ограничена 1024 символами, у sendMessage — 4096
TELEGRAM_CAPTION_LIMIT = 1024


def _mark_as_sent(posts):
    # помечаем посты отправленными ЗДЕСЬ, внутри send_digest, а не в коде,
    # который её вызывает — раньше это делали отдельно fetch_new_posts и
    # send_recent_matching_ads, и любой другой вызов send_digest (например,
    # разовая ручная отправка примера объявления) эту отметку пропускал,
    # из-за чего такой пост мог потом снова найтись плановым сканом или
    # "Применить" и уйти пользователю второй раз
    if not posts:
        return
    sent_ids_list = load_json(STATE_PATH, {}).get("sent_post_ids", [])
    sent_ids_set = set(sent_ids_list)
    new_keys = [k for p in posts if (k := _post_key(p)) not in sent_ids_set]
    if new_keys:
        save_state(sent_post_ids=(sent_ids_list + new_keys)[-SENT_POST_IDS_LIMIT:])


def send_digest(posts):
    for p in posts:
        message = format_post_message(p)
        photos = p.get("photos") or []
        fits_caption = len(message) <= TELEGRAM_CAPTION_LIMIT

        if len(photos) > 1:
            # альбом — все фото одним сообщением-группой, подпись вешаем на
            # первое фото (Telegram не даёт подпись под каждым в отдельности)
            if fits_caption:
                if send_telegram_media_group(photos, caption=message, parse_mode="HTML"):
                    continue
            else:
                if send_telegram_media_group(photos):
                    send_telegram_message(message, parse_mode="HTML")
                    continue
            # альбом не отправился (например, все ссылки на файлы устарели) —
            # пробуем как одно фото, а если и оно не выйдет — просто текстом
            photos = photos[:1]

        photo_url = photos[0] if photos else None

        if photo_url and fits_caption:
            if send_telegram_photo(photo_url, caption=message, parse_mode="HTML"):
                continue
            # не получилось с фото (например, ссылка на файл устарела) — шлём текстом
        elif photo_url:
            # текст не влезает в подпись — шлём фото отдельно, а следом полный текст
            if send_telegram_photo(photo_url):
                send_telegram_message(message, parse_mode="HTML")
                continue

        send_telegram_message(message, parse_mode="HTML")

    _mark_as_sent(posts)


def _telegram_api(method, data=None, files=None, timeout=15):
    # общая точка для всех вызовов Bot API — раньше каждая из функций ниже
    # сама собирала URL, дёргала requests.post и логировала ошибку, теперь
    # это в одном месте
    url = f"https://api.telegram.org/bot{BOT_TOKEN}/{method}"
    try:
        resp = requests.post(url, data=data, files=files, timeout=timeout)
        if not resp.ok:
            log(f"Ошибка {method}: {resp.text}")
            return None
        return resp.json().get("result")
    except requests.RequestException as e:
        log(f"Не удалось выполнить {method}: {e}")
        return None


def send_telegram_message(text, parse_mode=None, reply_markup=None):
    # без disable_web_page_preview на ссылку "Источник" Telegram сам
    # подтягивает большое превью с фото и текстом исходного канала — оно
    # перекрывает нашу карточку
    data = {"chat_id": MY_CHAT_ID, "text": text, "disable_web_page_preview": True}
    if parse_mode:
        data["parse_mode"] = parse_mode
    if reply_markup:
        data["reply_markup"] = json.dumps(reply_markup)
    return _telegram_api("sendMessage", data=data)


def answer_callback_query(callback_query_id, text=None):
    data = {"callback_query_id": callback_query_id}
    if text:
        data["text"] = text
    _telegram_api("answerCallbackQuery", data=data)


def edit_message_reply_markup(chat_id, message_id, reply_markup):
    data = {
        "chat_id": chat_id,
        "message_id": message_id,
        "reply_markup": json.dumps(reply_markup),
    }
    _telegram_api("editMessageReplyMarkup", data=data)


def send_telegram_photo(photo_url, caption=None, parse_mode=None):
    data = {"chat_id": MY_CHAT_ID}
    if caption:
        data["caption"] = caption
    if parse_mode:
        data["parse_mode"] = parse_mode
    try:
        # Telegram сам не может скачать эту картинку с CDN канала (отдаёт
        # "failed to get HTTP URL content"), поэтому качаем её сами и
        # заливаем файлом, а не просто передаём ссылку
        img = requests.get(photo_url, headers=HEADERS, timeout=15)
        img.raise_for_status()
    except requests.RequestException as e:
        log(f"Не удалось скачать фото для отправки: {e}")
        return False
    files = {"photo": ("photo.jpg", img.content)}
    return _telegram_api("sendPhoto", data=data, files=files, timeout=20) is not None


def send_telegram_media_group(photo_urls, caption=None, parse_mode=None):
    # Telegram принимает максимум 10 фото в одной группе
    photo_urls = photo_urls[:10]

    files = {}
    media = []
    for i, photo_url in enumerate(photo_urls):
        try:
            img = requests.get(photo_url, headers=HEADERS, timeout=15)
            img.raise_for_status()
        except requests.RequestException as e:
            log(f"Не удалось скачать фото {i} для альбома: {e}")
            continue
        field = f"photo{i}"
        files[field] = (f"{field}.jpg", img.content)
        item = {"type": "photo", "media": f"attach://{field}"}
        if i == 0 and caption:
            item["caption"] = caption
            if parse_mode:
                item["parse_mode"] = parse_mode
        media.append(item)

    if not media:
        return False

    data = {"chat_id": MY_CHAT_ID, "media": json.dumps(media)}
    return _telegram_api("sendMediaGroup", data=data, files=files, timeout=40) is not None


