def main():
    # команды/кнопки теперь обрабатывает непрерывный слушатель (--listen,
    # задача RoomBotListener) через long polling — если здесь тоже дёргать
    # getUpdates, Telegram отдаёт 409 Conflict (нельзя два одновременных
    # опроса для одного токена). Эта задача занимается только каналами.
    if "--commands-only" in sys.argv:
        process_commands()
        return
    posts = fetch_new_posts(config["channels"], config["filters"])
    send_digest(posts)


if __name__ == "__main__":
    try:
        if "--listen" in sys.argv:
            listen_loop()
        else:
            main()
    except Exception as e:
        log(f"Необработанная ошибка: {e}")
        raise
